-- ── Color ────────────────────────────────────────────────────────
T.describe("love.graphics.setColor / getColor", function()
    T.it("stores 0-1 components and returns them", function()
        love.graphics.setColor(0.5, 0.25, 1.0, 0.8)
        local r, g, b, a = love.graphics.getColor()
        T.near(r, 0.5); T.near(g, 0.25); T.near(b, 1.0); T.near(a, 0.8)
    end)

    T.it("alpha defaults to 1 when omitted", function()
        love.graphics.setColor(1, 0, 0)
        local _, _, _, a = love.graphics.getColor()
        T.near(a, 1)
    end)

    T.it("accepts a table argument", function()
        love.graphics.setColor({0.1, 0.2, 0.3, 0.4})
        local r, g, b, a = love.graphics.getColor()
        T.near(r, 0.1); T.near(g, 0.2); T.near(b, 0.3); T.near(a, 0.4)
    end)

    T.it("maps to 0-255 platform color correctly (white stays white)", function()
        love.graphics.setColor(1, 1, 1, 1)
        local c = lv1lua.current.color
        T.eq(c.r, 255); T.eq(c.g, 255); T.eq(c.b, 255); T.eq(c.a, 255)
    end)

    T.it("maps 0.5 to 128", function()
        love.graphics.setColor(0.5, 0.5, 0.5, 1)
        T.eq(lv1lua.current.color.r, 128)
    end)
end)

