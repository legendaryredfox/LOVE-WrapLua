describe("transform stack in C", function()
    local g = love.graphics
    local function near(a, b) ok(math.abs(a - b) < 1e-9, "want " .. b .. ", got " .. a) end
    it("shear(kx, ky) maps x' = x + kx*y and y' = y + ky*x", function()
        g.origin(); g.shear(0.5, 0.25)
        local x, y = g.transformPoint(4, 8); near(x, 8); near(y, 9)
        g.origin()
    end)
    it("a rotation turns the positions that follow it, translate after rotate moves along the turned axes", function()
        g.origin(); g.rotate(math.pi / 2); g.translate(10, 0)
        local x, y = g.transformPoint(0, 0); near(x, 0); near(y, 10)
        g.origin()
    end)
    it("push and pop restore the matrix", function()
        g.origin(); g.translate(5, 6); g.push(); g.scale(2); g.shear(1, 0); g.pop()
        local x, y = g.transformPoint(1, 1); near(x, 6); near(y, 7)
        g.origin()
    end)
    it("inverseTransformPoint undoes translate, scale, rotate and shear", function()
        g.origin(); g.translate(10, 20); g.scale(2, 3); g.rotate(0.4); g.shear(0.5, 0.2)
        local sx, sy = g.transformPoint(7, -3)
        local x, y = g.inverseTransformPoint(sx, sy); near(x, 7); near(y, -3)
        g.origin()
    end)
    it("applyTransform composes a Transform, replaceTransform replaces the matrix", function()
        g.origin(); g.translate(100, 0)
        local t = { _m = { 2, 0, 0, 0, 3, 0, 5, 6, 1 } }
        g.applyTransform(t)
        local x, y = g.transformPoint(1, 1); near(x, 107); near(y, 9)
        g.replaceTransform(t)
        x, y = g.transformPoint(1, 1); near(x, 7); near(y, 9)
        g.origin()
    end)
    it("a singular matrix leaves inverseTransformPoint unchanged", function()
        g.origin(); g.scale(0, 1)
        local x, y = g.inverseTransformPoint(3, 4); near(x, 3); near(y, 4)
        g.origin()
    end)
end)

