-- ── SpriteBatch ──────────────────────────────────────────────────
T.describe("love.graphics.newSpriteBatch", function()
    T.it("getCount starts at 0", function()
        local img = love.graphics.newImage("sprite.png")
        local sb  = love.graphics.newSpriteBatch(img, 100)
        T.eq(sb:getCount(), 0)
    end)

    T.it("add increments count", function()
        local img = love.graphics.newImage("sprite.png")
        local sb  = love.graphics.newSpriteBatch(img, 100)
        sb:add(0, 0)
        sb:add(10, 10)
        T.eq(sb:getCount(), 2)
    end)

    T.it("clear resets count to 0", function()
        local img = love.graphics.newImage("sprite.png")
        local sb  = love.graphics.newSpriteBatch(img, 100)
        sb:add(0, 0); sb:add(10, 10)
        sb:clear()
        T.eq(sb:getCount(), 0)
    end)

    T.it("getImage returns the source image", function()
        local img = love.graphics.newImage("sprite.png")
        local sb  = love.graphics.newSpriteBatch(img, 100)
        T.ok(sb:getImage() == img)
    end)
end)

