-- ── Transform stack ──────────────────────────────────────────────
T.describe("love.graphics transform stack", function()
    T.it("transformPoint with identity returns the same point", function()
        love.graphics.reset()
        local x, y = love.graphics.transformPoint(5, 10)
        T.near(x, 5); T.near(y, 10)
    end)

    T.it("translate shifts transformPoint result", function()
        love.graphics.reset()
        love.graphics.translate(100, 50)
        local x, y = love.graphics.transformPoint(0, 0)
        T.near(x, 100)
        T.near(y, 50)
    end)

    T.it("scale multiplies transformPoint", function()
        love.graphics.reset()
        love.graphics.scale(2, 3)
        local x, y = love.graphics.transformPoint(4, 5)
        T.near(x, 8)
        T.near(y, 15)
    end)

    T.it("origin() resets current transform level to identity", function()
        love.graphics.reset()
        love.graphics.translate(999, 999)
        love.graphics.origin()
        local x, y = love.graphics.transformPoint(0, 0)
        T.near(x, 0); T.near(y, 0)
    end)

    T.it("push/pop isolates transforms", function()
        love.graphics.reset()
        love.graphics.push()
        love.graphics.translate(200, 200)
        love.graphics.pop()
        local x, y = love.graphics.transformPoint(0, 0)
        T.near(x, 0); T.near(y, 0)
    end)

    T.it("inverseTransformPoint undoes transformPoint", function()
        love.graphics.reset()
        love.graphics.scale(2, 2)
        love.graphics.translate(10, 20)
        local tx, ty = love.graphics.transformPoint(5, 5)
        local ix, iy = love.graphics.inverseTransformPoint(tx, ty)
        T.near(ix, 5, 1e-4)
        T.near(iy, 5, 1e-4)
    end)
end)

