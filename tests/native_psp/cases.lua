describe("ffi shim", function()
    local ffi = dofile("psp_ffi.lua")
    it("byte buffer new/copy/string with pointer arithmetic", function()
        local b = ffi.new("uint8_t[?]", 16); ffi.copy(b, "hello", 5); ffi.copy(b + 5, " you", 4)
        eq(ffi.string(b, 9), "hello you"); b[0] = 72; eq(ffi.string(b, 3), "Hel"); eq(b[1], 101)
    end)
    it("int16/int32 roundtrip through bytes (incl. negatives)", function()
        local b = ffi.new("uint8_t[?]", 8)
        ffi.copy(b, ffi.new("int16_t[1]", -2), 2); eq(b[0], 254); eq(b[1], 255)
        local x = ffi.new("int16_t[1]"); ffi.copy(x, b, 2); eq(x[0], -2)
        ffi.copy(b, ffi.new("int32_t[1]", -100000), 4)
        local y = ffi.new("int32_t[1]"); ffi.copy(y, b, 4); eq(y[0], -100000)
    end)
    it("double roundtrip", function()
        for _, v in ipairs({ 0, 1, -1, 0.5, 3.25, -1234.5, 1e10, 1 / 3 }) do
            local b = ffi.new("uint8_t[?]", 8); ffi.copy(b, ffi.new("double[1]", v), 8)
            local d = ffi.new("double[1]"); ffi.copy(d, b, 8)
            ok(math.abs(d[0] - v) <= math.abs(v) * 1e-6, "double " .. v .. " -> " .. d[0])
        end
        local b = ffi.new("uint8_t[?]", 8); ffi.copy(b, ffi.new("double[1]", 1), 8)
        eq(b[7], 0x3F); eq(b[6], 0xF0)  -- IEEE-754 1.0 = 3FF0 0000 0000 0000
    end)
    it("cast of a string and sizeof", function()
        local p = ffi.cast("uint8_t*", "AB"); eq(p[0], 65); eq(p[1], 66); eq(ffi.sizeof("double[2]"), 16)
    end)
    it("struct typedef + metatype + istype", function()
        ffi.cdef("typedef struct { unsigned short id; char x; } t1;")
        local T = ffi.metatype("t1", {})
        local t = T(7, 3); eq(t.id, 7); eq(t.x, 3); t.id = 9; eq(t.id, 9)
        ok(ffi.istype(T, t)); ok(not ffi.istype(T, {})); eq(t.__isGCTile, true); eq(T().id, 0)
    end)
    it("jit and table stubs", function() ok(jit.off); jit.off(); jit.opt.start(3); local t = { 1 }; table.clear(t); eq(next(t), nil) end)
    it("newFileData(path) + getPointer feed ffi.cast", function()
        local fd = love.filesystem.newFileData("chunk.lua"); eq(fd:getSize(), 10)
        local p = ffi.cast("uint8_t*", fd:getPointer()); eq(p[0], 114)  -- "r" of "return 42"
    end)
end)

